import { Simulation } from '../../src/engine/sim';
import { serializeWorld } from '../../src/engine/serialize';
import { writeFileSync } from 'fs';
const seed = Number(process.argv[2] ?? 1), years = Number(process.argv[3] ?? 200);
const sim = Simulation.create({ seed });
let t = performance.now();
sim.runYears(years, (s) => { if (s.year % 25 === 0) { console.log(s.year, s.w.persons.size, ((performance.now() - t) / 25).toFixed(0) + 'ms/yr'); t = performance.now(); } });
const str = serializeWorld(sim.w);
writeFileSync(`tools/out/seed${seed}_y${years}.json`, str);
console.log('saved', (str.length / 1e6).toFixed(1), 'MB');
